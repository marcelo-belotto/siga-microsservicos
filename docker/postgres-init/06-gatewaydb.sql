-- Script DDL para o banco de dados do api-gateway (gatewaydb)
-- Domínio de autenticação: usuario e log_acesso.
-- No monolito, "usuario" tinha uma FK para "professor". Como Professor agora
-- pertence ao academico-service (outro banco), esse vínculo foi substituído
-- por uma coluna simples (professor_codigo_funcional), sem FK entre bancos.

SET statement_timeout = 0;
SET lock_timeout = 0;
SET idle_in_transaction_session_timeout = 0;
SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SELECT pg_catalog.set_config('search_path', '', false);
SET check_function_bodies = false;
SET xmloption = content;
SET client_min_messages = warning;
SET row_security = off;

--
-- Tabela: usuario
--
CREATE TABLE IF NOT EXISTS public.usuario (
    id integer NOT NULL,
    codigo character varying(255) NOT NULL,
    nome_completo character varying(255) NOT NULL,
    email character varying(255) NOT NULL,
    login character varying(255) NOT NULL,
    senha character varying(255) NOT NULL,
    role character varying(255) NOT NULL,
    data_cadastro timestamp(6) without time zone NOT NULL,
    data_expiracao_senha date,
    ativo boolean NOT NULL,
    tentativas_login integer NOT NULL DEFAULT 0,
    bloqueado boolean NOT NULL DEFAULT false,
    primeiro_acesso boolean NOT NULL DEFAULT true,
    professor_codigo_funcional character varying(255),
    CONSTRAINT usuario_role_check CHECK (((role)::text = ANY ((ARRAY['ADMIN'::character varying, 'COORDENADOR'::character varying, 'OPERADOR'::character varying, 'PROFESSOR'::character varying])::text[])))
);

ALTER TABLE public.usuario ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.usuario_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.usuario
    ADD CONSTRAINT usuario_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.usuario
    ADD CONSTRAINT usuario_codigo_key UNIQUE (codigo);
ALTER TABLE ONLY public.usuario
    ADD CONSTRAINT usuario_login_key UNIQUE (login);

--
-- Tabela: log_acesso
--
CREATE TABLE IF NOT EXISTS public.log_acesso (
    id bigint NOT NULL,
    usuario character varying(255) NOT NULL,
    data_hora timestamp(6) without time zone NOT NULL,
    operacao character varying(255) NOT NULL,
    resultado character varying(255) NOT NULL,
    detalhes character varying(255)
);

ALTER TABLE public.log_acesso ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.log_acesso_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.log_acesso
    ADD CONSTRAINT log_acesso_pkey PRIMARY KEY (id);
