-- Script DDL para o banco de dados do microsserviço avaliacao-service (avaliacaodb)
-- Baseado no DDL_dump.sql do monolito

SET statement_timeout = 0;
SET lock_timeout = 0;
SET idle_in_transaction_session_timeout = 0;
SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SELECT pg_catalog.set_config('search_path', '', false);
SET check_function_bodies = false;
SET xmloption = content;
SET client_min_messages = warning;
SET row_security = off;

--
-- Tabela: avaliacao
--
CREATE TABLE IF NOT EXISTS public.avaliacao (
    id integer NOT NULL,
    turma_id integer NOT NULL,
    disciplina_id integer NOT NULL,
    bimestre integer NOT NULL,
    data_exata date NOT NULL,
    conteudo character varying(255),
    tipo_avaliacao character varying(255) NOT NULL
);

ALTER TABLE public.avaliacao ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.avaliacao_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY public.avaliacao
    ADD CONSTRAINT avaliacao_pkey PRIMARY KEY (id);

--
-- Tabela: frequencia
--
CREATE TABLE IF NOT EXISTS public.frequencia (
    id integer NOT NULL,
    turma_id integer NOT NULL,
    disciplina_id integer NOT NULL,
    aluno_id integer NOT NULL,
    data date NOT NULL,
    numero_aula integer NOT NULL,
    status character varying(255) NOT NULL,
    justificativa character varying(255)
);

ALTER TABLE public.frequencia ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.frequencia_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY public.frequencia
    ADD CONSTRAINT frequencia_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.frequencia
    ADD CONSTRAINT frequencia_unique UNIQUE (turma_id, disciplina_id, aluno_id, data, numero_aula);

--
-- Tabela: nota
--
CREATE TABLE IF NOT EXISTS public.nota (
    id integer NOT NULL,
    turma_id integer NOT NULL,
    disciplina_id integer NOT NULL,
    aluno_id integer NOT NULL,
    periodo integer NOT NULL,
    tipo_avaliacao character varying(255) NOT NULL,
    valor double precision NOT NULL,
    data_lancamento date NOT NULL,
    usuario_lancamento character varying(255)
);

ALTER TABLE public.nota ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.nota_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY public.nota
    ADD CONSTRAINT nota_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.nota
    ADD CONSTRAINT nota_unique UNIQUE (turma_id, disciplina_id, aluno_id, periodo, tipo_avaliacao);
