-- Script DDL para o banco de dados do microsserviço matricula-service (matriculadb)
-- Extraído da tabela "matricula" do DDL_dump.sql do monolito.
-- As colunas aluno_id e turma_id eram FKs para as tabelas "aluno" e "turma"
-- no monolito. Como Aluno pertence ao aluno-service e Turma ao academico-service
-- (bancos de dados distintos), essas FKs foram removidas: o desacoplamento
-- entre serviços é feito via API Gateway. Os campos permanecem como simples
-- colunas integer NOT NULL, consistente com a entidade Matricula já migrada
-- (que também traz campos desnormalizados de aluno/turma para evitar joins remotos).

SET statement_timeout = 0;
SET lock_timeout = 0;
SET idle_in_transaction_session_timeout = 0;
SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SELECT pg_catalog.set_config('search_path', '', false);
SET check_function_bodies = false;
SET xmloption = content;
SET client_min_messages = warning;
SET row_security = off;

--
-- Tabela: matricula
--
CREATE TABLE IF NOT EXISTS public.matricula (
    id integer NOT NULL,
    numero character varying(255) NOT NULL,
    aluno_id integer NOT NULL,
    aluno_nome character varying(255),
    aluno_ra character varying(255),
    turma_id integer NOT NULL,
    turma_identificacao character varying(255),
    ano_letivo integer NOT NULL,
    serie integer NOT NULL,
    turno character varying(255) NOT NULL,
    data_matricula date NOT NULL,
    situacao character varying(255) NOT NULL,
    motivo_cancelamento character varying(255),
    data_cancelamento date,
    CONSTRAINT matricula_situacao_check CHECK (((situacao)::text = ANY ((ARRAY['ATIVA'::character varying, 'TRANCADA'::character varying, 'CANCELADA'::character varying, 'CONCLUIDA'::character varying])::text[]))),
    CONSTRAINT matricula_turno_check CHECK (((turno)::text = ANY ((ARRAY['MATUTINO'::character varying, 'VESPERTINO'::character varying])::text[])))
);

ALTER TABLE public.matricula ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.matricula_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.matricula
    ADD CONSTRAINT matricula_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.matricula
    ADD CONSTRAINT matricula_numero_key UNIQUE (numero);
