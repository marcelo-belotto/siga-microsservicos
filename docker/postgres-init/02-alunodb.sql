--
-- Tabela: aluno
--
CREATE TABLE IF NOT EXISTS public.aluno (
    id integer NOT NULL,
    ativo boolean NOT NULL,
    data_nascimento date NOT NULL,
    cpf character varying(11) NOT NULL,
    cpf_responsavel character varying(11) NOT NULL,
    nome character varying(100) NOT NULL,
    email character varying(255) NOT NULL,
    nome_responsavel character varying(255) NOT NULL,
    ra character varying(255) NOT NULL
);

--
-- Sequência de ID (Identity)
--
ALTER TABLE public.aluno ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.aluno_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

--
-- Chave Primária
--
ALTER TABLE ONLY public.aluno
    ADD CONSTRAINT aluno_pkey PRIMARY KEY (id);

--
-- Constraints de Unicidade
--
ALTER TABLE ONLY public.aluno
    ADD CONSTRAINT aluno_cpf_key UNIQUE (cpf);

ALTER TABLE ONLY public.aluno
    ADD CONSTRAINT aluno_email_key UNIQUE (email);

ALTER TABLE ONLY public.aluno
    ADD CONSTRAINT aluno_ra_key UNIQUE (ra);
