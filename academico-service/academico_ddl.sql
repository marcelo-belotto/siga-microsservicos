--
-- Tabela: modelo_grade_aula
--
CREATE TABLE IF NOT EXISTS public.modelo_grade_aula (
    id integer NOT NULL,
    modelo_grade_id integer NOT NULL,
    disciplina_id integer NOT NULL,
    dia_semana character varying(255) NOT NULL,
    numero_aula integer NOT NULL,
    CONSTRAINT modelo_grade_aula_dia_semana_check CHECK (((dia_semana)::text = ANY ((ARRAY['MONDAY'::character varying, 'TUESDAY'::character varying, 'WEDNESDAY'::character varying, 'THURSDAY'::character varying, 'FRIDAY'::character varying, 'SATURDAY'::character varying, 'SUNDAY'::character varying])::text[]))),
    CONSTRAINT modelo_grade_aula_numero_aula_check CHECK (((numero_aula <= 5) AND (numero_aula >= 1)))
);

ALTER TABLE public.modelo_grade_aula ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.modelo_grade_aula_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.modelo_grade_aula
    ADD CONSTRAINT modelo_grade_aula_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.modelo_grade_aula
    ADD CONSTRAINT modelo_grade_aula_modelo_grade_id_dia_semana_numero_aula_key UNIQUE (modelo_grade_id, dia_semana, numero_aula);
ALTER TABLE ONLY public.modelo_grade_aula
    ADD CONSTRAINT fk_modelo_grade_aula_modelo_grade
    FOREIGN KEY (modelo_grade_id) REFERENCES public.modelo_grade(id);
ALTER TABLE ONLY public.modelo_grade_aula
    ADD CONSTRAINT fk_modelo_grade_aula_disciplina
    FOREIGN KEY (disciplina_id) REFERENCES public.disciplina(id);

--
-- Tabela: turma
--
CREATE TABLE IF NOT EXISTS public.turma (
    id integer NOT NULL,
    codigo character varying(255) NOT NULL,
    ano_letivo integer NOT NULL,
    serie integer NOT NULL,
    nome character varying(255) NOT NULL,
    turno character varying(255) NOT NULL,
    professor_regente_id integer,
    modelo_grade_id integer,
    ativo boolean NOT NULL,
    aulas_por_dia integer NOT NULL,
    CONSTRAINT turma_serie_check CHECK (((serie >= 1) AND (serie <= 5))),
    CONSTRAINT turma_turno_check CHECK (((turno)::text = ANY ((ARRAY['MATUTINO'::character varying, 'VESPERTINO'::character varying])::text[])))
);

ALTER TABLE public.turma ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.turma_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.turma
    ADD CONSTRAINT turma_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.turma
    ADD CONSTRAINT turma_codigo_key UNIQUE (codigo);
ALTER TABLE ONLY public.turma
    ADD CONSTRAINT turma_ano_letivo_serie_nome_turno_key UNIQUE (ano_letivo, serie, nome, turno);
ALTER TABLE ONLY public.turma
    ADD CONSTRAINT fk_turma_professor_regente
    FOREIGN KEY (professor_regente_id) REFERENCES public.professor(id);
ALTER TABLE ONLY public.turma
    ADD CONSTRAINT fk_turma_modelo_grade
    FOREIGN KEY (modelo_grade_id) REFERENCES public.modelo_grade(id);

