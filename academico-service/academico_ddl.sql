-- Script DDL para o banco de dados do microsserviço academico-service (academicodb)
-- Baseado no DDL_dump.sql do monolito
-- Tabelas do domínio acadêmico: ano_letivo, disciplina, professor, turma,
-- modelo_grade, grade_horaria e suas coleções/relações internas.
-- Chaves estrangeiras para outros domínios (aluno, matrícula, usuário) foram
-- removidas: o desacoplamento entre serviços é feito via API Gateway.

SET statement_timeout = 0;
SET lock_timeout = 0;
SET idle_in_transaction_session_timeout = 0;
SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SELECT pg_catalog.set_config('search_path', '', false);
SET check_function_bodies = false;
SET xmloption = content;
SET client_min_messages = warning;
SET row_security = off;

--
-- Tabela: ano_letivo
--
CREATE TABLE IF NOT EXISTS public.ano_letivo (
    id integer NOT NULL,
    ano integer NOT NULL,
    data_inicio date NOT NULL,
    data_encerramento date NOT NULL,
    dias_letivos integer,
    encerrado boolean NOT NULL
);

ALTER TABLE public.ano_letivo ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.ano_letivo_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.ano_letivo
    ADD CONSTRAINT ano_letivo_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.ano_letivo
    ADD CONSTRAINT ano_letivo_ano_key UNIQUE (ano);

--
-- Tabela: ano_letivo_feriados (coleção de datas do ano letivo)
--
CREATE TABLE IF NOT EXISTS public.ano_letivo_feriados (
    ano_letivo_id integer NOT NULL,
    data_feriado date
);

ALTER TABLE ONLY public.ano_letivo_feriados
    ADD CONSTRAINT fk_ano_letivo_feriados_ano_letivo
    FOREIGN KEY (ano_letivo_id) REFERENCES public.ano_letivo(id);

--
-- Tabela: ano_letivo_semanas_avaliacao (coleção @Embeddable do ano letivo)
--
CREATE TABLE IF NOT EXISTS public.ano_letivo_semanas_avaliacao (
    ano_letivo_id integer NOT NULL,
    bimestre integer,
    tipo character varying(255),
    data_inicio date,
    data_fim date
);

ALTER TABLE ONLY public.ano_letivo_semanas_avaliacao
    ADD CONSTRAINT fk_ano_letivo_semanas_avaliacao_ano_letivo
    FOREIGN KEY (ano_letivo_id) REFERENCES public.ano_letivo(id);

--
-- Tabela: disciplina
--
CREATE TABLE IF NOT EXISTS public.disciplina (
    id integer NOT NULL,
    codigo character varying(255) NOT NULL,
    descricao character varying(255) NOT NULL,
    carga_horaria_anual integer NOT NULL,
    ativo boolean NOT NULL,
    CONSTRAINT disciplina_carga_horaria_anual_check CHECK ((carga_horaria_anual >= 1))
);

ALTER TABLE public.disciplina ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.disciplina_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.disciplina
    ADD CONSTRAINT disciplina_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.disciplina
    ADD CONSTRAINT disciplina_codigo_key UNIQUE (codigo);

--
-- Tabela: professor
--
CREATE TABLE IF NOT EXISTS public.professor (
    id integer NOT NULL,
    nome character varying(100) NOT NULL,
    data_nascimento date NOT NULL,
    cpf character varying(11) NOT NULL,
    email character varying(255) NOT NULL,
    ativo boolean NOT NULL,
    codigo_funcional character varying(255) NOT NULL,
    especialidade character varying(255) NOT NULL,
    CONSTRAINT professor_especialidade_check CHECK (((especialidade)::text = ANY ((ARRAY['REGENTE'::character varying, 'ARTES'::character varying, 'EDUCACAO_FISICA'::character varying, 'INFORMATICA'::character varying, 'OUTROS'::character varying])::text[])))
);

ALTER TABLE public.professor ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.professor_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.professor
    ADD CONSTRAINT professor_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.professor
    ADD CONSTRAINT professor_codigo_funcional_key UNIQUE (codigo_funcional);
ALTER TABLE ONLY public.professor
    ADD CONSTRAINT professor_cpf_key UNIQUE (cpf);
ALTER TABLE ONLY public.professor
    ADD CONSTRAINT professor_email_key UNIQUE (email);

--
-- Tabela: modelo_grade
--
CREATE TABLE IF NOT EXISTS public.modelo_grade (
